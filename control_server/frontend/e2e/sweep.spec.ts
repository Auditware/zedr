  await run.timed('switch to all processes', async () => {
    await page.getByRole('radio', { name: 'All' }).click()
    await page.waitForFunction((count) => window.document.querySelectorAll('.react-flow__node').length > count, notable)
  })
  const all = (await canvasNodes(page)).length
  expect(all).toBeGreaterThan(notable)
